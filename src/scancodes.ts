export function resolveScancodes(keyCombo: string): string[] {
  const keys = keyCombo.toLowerCase().split("+").map(k => k.trim());
  const codes: number[] = [];

  // Press all keys (make codes)
  for (const key of keys) {
    const entry = SCANCODES[key];
    if (!entry) throw new Error(`Unknown key: "${key}". Available keys: ${Object.keys(SCANCODES).filter(k => !k.match(/^[a-z]$/) || k === key).slice(0, 30).join(", ")}...`);
    codes.push(...entry[0]);
  }

  // Release in reverse order (break codes)
  for (const key of [...keys].reverse()) {
    const entry = SCANCODES[key]!;
    codes.push(...entry[1]);
  }

  return codes.map(c => c.toString(16).padStart(2, "0"));
}

export function getAvailableKeys(): string[] {
  return [...new Set(Object.keys(SCANCODES))].sort();
}
